CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$declare
    full_name text;
    primer_nombre text;
    el_apellido text;
begin
  -- Aseguramos que tengamos un texto
  full_name := trim(coalesce(new.raw_user_meta_data->>'full_name', 'Usuario Google'));

  -- Si hay un espacio, separamos nombre y apellido
  if position(' ' in full_name) > 0 then
      primer_nombre := split_part(full_name, ' ', 1);
      el_apellido := substring(full_name from position(' ' in full_name) + 1);
  else
      primer_nombre := full_name;
      el_apellido := ' '; 
  end if;

  -- Hacemos el INSERT agregando el campo 'rol' que faltaba
  insert into public.usuarios (id, email, nombre, apellido, foto, telefono, rol)
  values (
    new.id,
    new.email,
    primer_nombre,
    el_apellido,
    'usuarios/default.png',
    '',
    'user' -- 🚀 ¡Acá le asignamos el rol por defecto para que no falle! (Cambiá 'user' si usan otro string)
  );
  return new;
exception when others then
  return new;
end;$function$
;

