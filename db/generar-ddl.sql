-- =====================================================================
-- Genera el DDL del esquema public (equivalente a pg_dump --schema-only)
-- Uso: pegar en Supabase → SQL Editor → Run, copiar la única celda del
-- resultado y guardarla como db/schema.sql. No incluye datos.
-- =====================================================================
WITH
tablas AS (
    SELECT c.oid, c.relname, c.relrowsecurity
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'e')
),
tipos AS (  -- enums propios
    SELECT 10 AS orden, t.typname AS nombre,
           format('CREATE TYPE public.%I AS ENUM (%s);', t.typname,
                  (SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder)
                   FROM pg_enum e WHERE e.enumtypid = t.oid)) AS sql
    FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public' AND t.typtype = 'e'
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = t.oid AND d.deptype = 'e')
),
secuencias AS (
    SELECT 20, c.relname,
           format('CREATE SEQUENCE public.%I AS %s START WITH %s INCREMENT BY %s;',
                  c.relname, format_type(s.seqtypid, NULL), s.seqstart, s.seqincrement)
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace JOIN pg_sequence s ON s.seqrelid = c.oid
    WHERE n.nspname = 'public' AND c.relkind = 'S'
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype IN ('e', 'i'))
),
funciones AS (
    SELECT 30, p.proname, pg_get_functiondef(p.oid) || ';'
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.prokind IN ('f', 'p')
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
),
crear_tablas AS (
    SELECT 40, t.relname,
           format(E'CREATE TABLE public.%I (\n%s\n);', t.relname, string_agg(
               format('    %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                   CASE WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                        WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,
                   CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                        WHEN ad.adbin IS NOT NULL AND a.attidentity = '' THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
                        ELSE '' END,
                   CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END),
               E',\n' ORDER BY a.attnum))
    FROM tablas t
    JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped
    LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
    GROUP BY t.relname
),
secuencias_duenas AS (  -- serial: la secuencia queda asociada a su columna
    SELECT 45, c.relname,
           format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', c.relname, tc.relname, a.attname)
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_depend d ON d.objid = c.oid AND d.deptype = 'a' AND d.refobjsubid > 0
    JOIN pg_class tc ON tc.oid = d.refobjid
    JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
    WHERE n.nspname = 'public' AND c.relkind = 'S'
),
restricciones AS (  -- PK, UNIQUE y CHECK primero; claves foráneas al final
    SELECT CASE WHEN co.contype = 'f' THEN 70 ELSE 50 END, t.relname || '.' || co.conname,
           format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
    FROM pg_constraint co JOIN tablas t ON t.oid = co.conrelid
    WHERE co.contype IN ('p', 'u', 'c', 'f', 'x')
),
indices AS (  -- los que no vienen de una restricción
    SELECT 60, i.relname, pg_get_indexdef(i.oid) || ';'
    FROM pg_index x JOIN tablas t ON t.oid = x.indrelid JOIN pg_class i ON i.oid = x.indexrelid
    WHERE NOT EXISTS (SELECT 1 FROM pg_constraint co WHERE co.conindid = x.indexrelid)
),
disparadores AS (
    SELECT 80, tg.tgname, pg_get_triggerdef(tg.oid) || ';'
    FROM pg_trigger tg JOIN tablas t ON t.oid = tg.tgrelid
    WHERE NOT tg.tgisinternal
),
vistas AS (
    SELECT 85, c.relname, format(E'CREATE VIEW public.%I AS\n%s', c.relname, pg_get_viewdef(c.oid))
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'v'
),
rls AS (
    SELECT 90, relname, format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', relname)
    FROM tablas WHERE relrowsecurity
),
politicas AS (
    SELECT 95, tablename || '.' || policyname,
           format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;',
                  policyname, tablename, permissive, cmd, array_to_string(roles, ', '),
                  COALESCE(' USING (' || qual || ')', ''), COALESCE(' WITH CHECK (' || with_check || ')', ''))
    FROM pg_policies WHERE schemaname = 'public'
),
todo AS (
    SELECT * FROM tipos UNION ALL SELECT * FROM secuencias UNION ALL SELECT * FROM funciones
    UNION ALL SELECT * FROM crear_tablas UNION ALL SELECT * FROM secuencias_duenas
    UNION ALL SELECT * FROM restricciones UNION ALL SELECT * FROM indices
    UNION ALL SELECT * FROM disparadores UNION ALL SELECT * FROM vistas
    UNION ALL SELECT * FROM rls UNION ALL SELECT * FROM politicas
)
SELECT '-- Esquema public de SheliGo (solo estructura, sin datos)' || E'\n'
       || '-- Generado con db/generar-ddl.sql el ' || to_char(now(), 'YYYY-MM-DD') || E'\n\n'
       || string_agg(sql, E'\n\n' ORDER BY orden, nombre) AS ddl
FROM todo;
